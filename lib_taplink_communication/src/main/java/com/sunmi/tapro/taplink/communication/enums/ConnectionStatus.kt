package com.sunmi.tapro.taplink.communication.enums

/**
 * Connection Status Enum
 * 
 * Defines various states for service connection
 * 
 * @author TaPro Team
 * @since 2025-01-XX
 */
enum class ConnectionStatus {
    /**
     * Disconnected
     */
    DISCONNECTED,
    
    /**
     * Connecting
     */
    CONNECTING,
    
    /**
     * Connected
     */
    CONNECTED,
    
    /**
     * Reconnecting
     */
    RECONNECTING,
    
    /**
     * Connection Error
     */
    ERROR
}













